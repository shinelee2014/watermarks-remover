async function callBackendClean(file) {
  const arrayBuffer = await file.arrayBuffer();
  const base64 = btoa(String.fromCharCode(...new Uint8Array(arrayBuffer)));

  const headers = { "Content-Type": "application/json" };
  if (AppState.backendApiKey) {
    headers["Authorization"] = `Bearer ${AppState.backendApiKey}`;
  }

  const res = await fetch(`${AppState.backendUrl}/clean`, {
    method: "POST",
    headers,
    body: JSON.stringify({
      file: base64,
      name: file.name
    })
  });

  const json = await res.json();
  if (!json.ok) throw new Error(json.error || "后端清洗失败");

  const binaryString = atob(json.cleaned);
  const bytes = new Uint8Array(binaryString.length);
  for (let i = 0; i < binaryString.length; i++) {
    bytes[i] = binaryString.charCodeAt(i);
  }

  return {
    blob: new Blob([bytes], { type: file.type || "application/octet-stream" }),
    report: json.report
  };
}
