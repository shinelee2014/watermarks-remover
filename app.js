const AI_META_HINTS = [
  "c2pa", "contentcredentials", "digitalSourceType", "trainedAlgorithmicMedia",
  "compositeWithTrainedAlgorithmicMedia", "algorithmicMedia", "AIGC", "AI generated",
  "Generated by", "Claude", "Anthropic", "OpenAI", "SynthID", "ChatGPT", "Midjourney", "Stable Diffusion"
];

const AI_FRONTMATTER_KEYS = new Set([
  "generator", "ai", "ai_generated", "ai-generated", "claude", "anthropic",
  "openai", "gemini", "synthid", "c2pa", "content_credentials", "contentcredentials",
  "provenance", "digital_source_type", "digitalsourcetype", "created_with", "createdwith", "model", "llm"
]);

/**
 * Layer A: Text Unicode Sanitizer
 */
function cleanTextEngine(text, options = {}) {
  const normalizeSpaces = options.normalizeSpaces !== false;
  const preserveEmoji = options.preserveEmoji !== false;

  let outChars = [];
  let hits = new Map(); // key -> { codepoint, kind, count, samples }
  let prevKept = null;

  for (let i = 0; i < text.length; i++) {
    const codePoint = text.codePointAt(i);
    const char = String.fromCodePoint(codePoint);
    if (char.length > 1) i++; // Surrogate pair advance

    let action = "keep";
    let outChar = char;
    let kind = null;

    // Check Emoji glue
    if (preserveEmoji && isEmojiGlue(codePoint) && prevKept && isEmojiBase(prevKept.codePointAt(0))) {
      action = "keep";
    } else if (preserveEmoji && isScriptJoiner(codePoint) && prevKept && prevKept.codePointAt(0) > 0x7F) {
      action = "keep";
    } else if (STRIP_CODEPOINTS.has(codePoint) || (codePoint >= 0xE0100 && codePoint < 0xE01F0) || isTagChar(codePoint) || isPrivateUse(codePoint)) {
      action = "strip";
      kind = getCharKind(codePoint);
    } else if (normalizeSpaces && SPACE_HOMOGLYPHS[codePoint]) {
      action = "replace";
      outChar = SPACE_HOMOGLYPHS[codePoint];
      kind = "space";
    }

    if (kind !== null) {
      const key = `${codePoint}_${kind}`;
      if (!hits.has(key)) {
        hits.set(key, {
          codepoint: codePoint,
          label: getCharLabel(codePoint),
          kind: kind,
          count: 0,
          confidence: kind === "space" ? "informational" : "probable",
          samples: []
        });
      }
      const hit = hits.get(key);
      hit.count++;
      if (hit.samples.length < 5) hit.samples.push(i);
    }

    if (action === "keep" || action === "replace") {
      outChars.push(outChar);
      prevKept = outChar;
    }
  }

  const cleanedText = outChars.join("");
  const hitsArray = Array.from(hits.values());
  const suspiciousTotal = hitsArray.reduce((acc, h) => acc + h.count, 0);

  return {
    cleanedText,
    hits: hitsArray,
    suspiciousTotal,
    inputLength: text.length,
    outputLength: cleanedText.length,
    removedCount: text.length - cleanedText.length
  };
}

/**
 * Markdown Sanitizer: Strips AI Frontmatter keys & runs Layer A
 */
function cleanMarkdownEngine(text, options = {}) {
  let cleaned = text;
  let actions = [];
  const fmMatch = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);

  if (fmMatch) {
    const block = fmMatch[1];
    const body = text.slice(fmMatch[0].length);
    const lines = block.split(/\r?\n/);
    const keptLines = [];

    for (let line of lines) {
      const m = line.match(/^([A-Za-z0-9_.-]+)\s*:(.*)$/);
      if (m) {
        const key = m[1].toLowerCase();
        const val = m[2].toLowerCase();
        const hasAIVal = AI_META_HINTS.some(h => val.includes(h.toLowerCase()));
        if (AI_FRONTMATTER_KEYS.has(key) || hasAIVal) {
          actions.push(`剥离 Frontmatter AI 键: ${m[1]}`);
          continue;
        }
      }
      keptLines.push(line);
    }

    if (keptLines.length > 0 && keptLines.some(l => l.trim())) {
      cleaned = `---\n${keptLines.join("\n").trim()}\n---\n${body}`;
    } else {
      cleaned = body.trimStart();
      actions.push("清理空 Frontmatter 块");
    }
  }

  const layerAResult = cleanTextEngine(cleaned, options);
  return {
    cleanedText: layerAResult.cleanedText,
    actions,
    layerAResult
  };
}

/**
 * HTML Sanitizer: Strips AI meta/JSON-LD & runs Layer A
 */
function cleanHTMLEngine(text, options = {}) {
  let actions = [];
  let cleaned = text;

  // 1. Strip meta generator if AI related
  cleaned = cleaned.replace(/<meta\b[^>]*>/gi, (tag) => {
    const isGenerator = /name\s*=\s*["']generator["']/i.test(tag) || /property\s*=\s*["']generator["']/i.test(tag);
    if (isGenerator) {
      const isAI = /claude|anthropic|openai|gemini|synthid|chatgpt|copilot/i.test(tag);
      if (isAI) {
        actions.push(`剥离 Meta Generator: ${tag.slice(0, 60)}`);
        return "";
      }
      return tag; // Keep CMS (WordPress, etc.)
    }
    if (/c2pa|content.?credential|ai[-_ ]?generated|aigc/i.test(tag)) {
      actions.push(`剥离 AI Meta 标签`);
      return "";
    }
    return tag;
  });

  // 2. Strip JSON-LD provenance
  cleaned = cleaned.replace(/<script\b[^>]*type\s*=\s*["']application\/ld\+json["'][^>]*>[\s\S]*?<\/script>/gi, (script) => {
    if (/DigitalSourceType|trainedAlgorithmicMedia|SoftwareAgent|c2pa/i.test(script)) {
      actions.push("剥离 JSON-LD AI 溯源数据块");
      return "";
    }
    return script;
  });

  // 3. Strip data-ai* attributes
  cleaned = cleaned.replace(/\sdata-ai[\w-]*\s*=\s*["'][^"']*["']/gi, () => {
    actions.push("剥离 data-ai* DOM 自定义属性");
    return "";
  });

  const layerAResult = cleanTextEngine(cleaned, options);
  return {
    cleanedText: layerAResult.cleanedText,
    actions,
    layerAResult
  };
}

/**
 * SVG Sanitizer: Strips <metadata>, RDF, XMP
 */
function cleanSVGEngine(text) {
  let actions = [];
  let cleaned = text;

  cleaned = cleaned.replace(/<metadata\b[^>]*>[\s\S]*?<\/metadata\s*>/gi, () => {
    actions.push("剥离 SVG <metadata> 块");
    return "";
  });

  cleaned = cleaned.replace(/<x:xmpmeta\b[^>]*>[\s\S]*?<\/x:xmpmeta\s*>/gi, () => {
    actions.push("剥离 Adobe XMP 块");
    return "";
  });

  cleaned = cleaned.replace(/<!--[\s\S]*?-->/gi, (cmt) => {
    if (/ai|claude|openai|gemini|synthid|c2pa|provenance/i.test(cmt)) {
      actions.push("剥离包含 AI 标记的 SVG 注释");
      return "";
    }
    return cmt;
  });

  return {
    cleanedText: cleaned,
    actions
  };
}

/**
 * PNG Binary Sanitizer: Drops caBX, juMB, jumb, and AI text/XMP chunks
 */
function cleanPNGBinary(buffer) {
  const bytes = new Uint8Array(buffer);
  const PNG_SIG = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];
  for (let i = 0; i < 8; i++) {
    if (bytes[i] !== PNG_SIG[i]) throw new Error("非有效 PNG 格式文件");
  }

  const chunks = [];
  let pos = 8;
  const view = new DataView(buffer);
  let strippedChunks = [];

  while (pos + 8 <= bytes.length) {
    const length = view.getUint32(pos, false);
    const typeBytes = bytes.slice(pos + 4, pos + 8);
    const type = String.fromCharCode(...typeBytes);
    const chunkStart = pos;
    const chunkEnd = pos + 12 + length;
    const data = bytes.slice(pos + 8, pos + 8 + length);

    let drop = false;
    // C2PA or Manifest chunks
    if (["caBX", "juMB", "jumb"].includes(type) || type.startsWith("c2")) {
      drop = true;
      strippedChunks.push(`C2PA Chunk (${type})`);
    } else if (["tEXt", "zTXt", "iTXt", "eXIf"].includes(type)) {
      // Check payload for AI hints
      const textDecoder = new TextDecoder("latin1");
      const textPayload = textDecoder.decode(data);
      const isAI = AI_META_HINTS.some(h => textPayload.toLowerCase().includes(h.toLowerCase()));
      if (isAI) {
        drop = true;
        strippedChunks.push(`AI Metadata Chunk (${type})`);
      }
    }

    if (!drop) {
      chunks.push(bytes.slice(chunkStart, chunkEnd));
    }

    if (type === "IEND") break;
    pos = chunkEnd;
  }

  // Combine kept chunks
  const totalLength = 8 + chunks.reduce((acc, c) => acc + c.length, 0);
  const out = new Uint8Array(totalLength);
  out.set(PNG_SIG, 0);
  let offset = 8;
  for (let c of chunks) {
    out.set(c, offset);
    offset += c.length;
  }

  return {
    cleanedBytes: out,
    actions: strippedChunks.length > 0 ? strippedChunks : ["无残留 C2PA/AI 元数据块"]
  };
}

/**
 * JPEG Binary Sanitizer: Drops APP11 (C2PA JUMBF) & strips APP1 AI markers
 */
function cleanJPEGBinary(buffer) {
  const bytes = new Uint8Array(buffer);
  if (bytes[0] !== 0xFF || bytes[1] !== 0xD8) throw new Error("非有效 JPEG 格式文件");

  let pos = 2;
  const keptSegments = [[0xFF, 0xD8]];
  let strippedActions = [];
  const textDecoder = new TextDecoder("latin1");

  while (pos < bytes.length) {
    if (bytes[pos] !== 0xFF) {
      pos++;
      continue;
    }
    while (pos < bytes.length && bytes[pos] === 0xFF) pos++;
    if (pos >= bytes.length) break;

    const marker = bytes[pos];
    pos++;

    if (marker === 0xD9) { // EOI
      keptSegments.push([0xFF, 0xD9]);
      break;
    }
    if (marker === 0xDA) { // SOS (Start of Scan) - rest is compressed image data
      keptSegments.push(bytes.slice(pos - 2));
      break;
    }
    if (marker >= 0xD0 && marker <= 0xD7) { // RSTn
      continue;
    }

    const segLen = (bytes[pos] << 8) | bytes[pos + 1];
    const segStart = pos - 2;
    const segEnd = pos + segLen;
    const segPayload = bytes.slice(pos + 2, segEnd);

    let drop = false;
    if (marker === 0xEB) { // APP11 (C2PA / JUMBF)
      drop = true;
      strippedActions.push("剥离 JPEG APP11 (C2PA/JUMBF 段)");
    } else if (marker === 0xE1) { // APP1 (EXIF / XMP)
      const text = textDecoder.decode(segPayload);
      if (AI_META_HINTS.some(h => text.toLowerCase().includes(h.toLowerCase()))) {
        drop = true;
        strippedActions.push("剥离 JPEG APP1 AI/C2PA 属性段");
      }
    }

    if (!drop) {
      keptSegments.push(bytes.slice(segStart, segEnd));
    }
    pos = segEnd;
  }

  // Combine segments
  let total = keptSegments.reduce((acc, s) => acc + (s.length || s.byteLength || 2), 0);
  let out = new Uint8Array(total);
  let offset = 0;
  for (let s of keptSegments) {
    const u8 = s instanceof Uint8Array ? s : new Uint8Array(s);
    out.set(u8, offset);
    offset += u8.length;
  }

  return {
    cleanedBytes: out,
    actions: strippedActions.length > 0 ? strippedActions : ["无额外 JPEG C2PA 段"]
  };
}

/**
 * DOCX Package Sanitizer (using client-side JSZip)
 */
async function cleanDOCXPackage(buffer) {
  if (typeof JSZip === "undefined") {
    throw new Error("JSZip 库未载入，无法在纯前端解压 DOCX");
  }

  const zip = await JSZip.loadAsync(buffer);
  const actions = [];

  // 1. Drop customXml
  const customXmlFiles = Object.keys(zip.files).filter(name => name.startsWith("customXml/"));
  for (let file of customXmlFiles) {
    zip.remove(file);
    actions.push(`剥离 DOCX 自定义数据块: ${file}`);
  }

  // 2. Clean docProps/core.xml, app.xml, custom.xml
  const metaFiles = ["docProps/core.xml", "docProps/app.xml", "docProps/custom.xml"];
  for (let metaName of metaFiles) {
    const metaFile = zip.file(metaName);
    if (metaFile) {
      let text = await metaFile.async("text");
      let modified = false;

      // Scrub creator, lastModifiedBy, Application
      text = text.replace(/(<dc:creator[^>]*>)([\s\S]*?)(<\/dc:creator>)/gi, (m, p1, inner, p3) => {
        if (AI_META_HINTS.some(h => inner.toLowerCase().includes(h.toLowerCase()))) {
          modified = true;
          actions.push(`清除 ${metaName} 中 dc:creator AI 标识`);
          return p1 + p3;
        }
        return m;
      });

      text = text.replace(/(<Application[^>]*>)([\s\S]*?)(<\/Application>)/gi, (m, p1, inner, p3) => {
        if (AI_META_HINTS.some(h => inner.toLowerCase().includes(h.toLowerCase()))) {
          modified = true;
          actions.push(`清除 ${metaName} 中 Application AI 生成器标记`);
          return p1 + p3;
        }
        return m;
      });

      if (modified) {
        zip.file(metaName, text);
      }
    }
  }

  const cleanedBlob = await zip.generateAsync({ type: "uint8array", compression: "DEFLATE" });
  return {
    cleanedBytes: cleanedBlob,
    actions: actions.length > 0 ? actions : ["DOCX 元数据结构已清洗"]
  };
}

