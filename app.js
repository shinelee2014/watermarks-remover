const STRIP_CODEPOINTS = new Set([
  0x00AD, // soft hyphen
  0x034F, // combining grapheme joiner
  0x061C, // Arabic letter mark
  0x115F, // Hangul choseong filler
  0x1160, // Hangul jungseong filler
  0x17B4, // Khmer vowel inherent AQ
  0x17B5, // Khmer vowel inherent AA
  0x180B, // Mongolian free variation selector-1
  0x180C, 0x180D,
  0x180E, // Mongolian vowel separator
  0x200B, // zero width space (ZWSP)
  0x200C, // zero width non-joiner (ZWNJ)
  0x200D, // zero width joiner (ZWJ)
  0x200E, // LRM
  0x200F, // RLM
  0x202A, 0x202B, 0x202C, 0x202D, 0x202E, // Bidi embedding / override / pop
  0x2060, // word joiner
  0x2061, 0x2062, 0x2063, 0x2064, // invisible operators
  0x2066, 0x2067, 0x2068, 0x2069, // Bidi isolates (LRI, RLI, FSI, PDI)
  0x206A, 0x206B, 0x206C, 0x206D, 0x206E, 0x206F,
  0xFEFF, // BOM / ZWNBSP
  0xFE00, 0xFE01, 0xFE02, 0xFE03, 0xFE04, 0xFE05, 0xFE06, 0xFE07,
  0xFE08, 0xFE09, 0xFE0A, 0xFE0B, 0xFE0C, 0xFE0D, 0xFE0E, 0xFE0F, // Variation Selectors
  0xFFF9, 0xFFFA, 0xFFFB, // Interlinear annotation
]);

const SPACE_HOMOGLYPHS = {
  0x00A0: " ", // no-break space
  0x1680: " ", // Ogham space mark
  0x2000: " ", // en quad
  0x2001: " ", // em quad
  0x2002: " ", // en space
  0x2003: " ", // em space
  0x2004: " ", // three-per-em space
  0x2005: " ", // four-per-em space
  0x2006: " ", // six-per-em space
  0x2007: " ", // figure space
  0x2008: " ", // punctuation space
  0x2009: " ", // thin space
  0x200A: " ", // hair space
  0x202F: " ", // narrow no-break space
  0x205F: " ", // medium mathematical space
  0x3000: " ", // ideographic fullwidth space
};

const BIDI_CODEPOINTS = new Set([
  0x061C, 0x200E, 0x200F, 0x202A, 0x202B, 0x202C, 0x202D, 0x202E,
  0x2066, 0x2067, 0x2068, 0x2069
]);

const ZW_FAMILY = new Set([0x200B, 0x200C, 0x200D, 0x2060, 0xFEFF, 0x180E]);

function isPrivateUse(cp) {
  return (cp >= 0xE000 && cp <= 0xF8FF) ||
         (cp >= 0xF0000 && cp <= 0xFFFFD) ||
         (cp >= 0x100000 && cp <= 0x10FFFD);
}

function isEmojiBase(cp) {
  if (cp >= 0x1F000 && cp <= 0x1FAFF) return true;
  if (cp >= 0x2600 && cp <= 0x27BF) return true;
  if (cp >= 0x2B00 && cp <= 0x2BFF) return true;
  if ([0x00A9, 0x00AE, 0x2122, 0x3030, 0x303D, 0x3297, 0x3299].includes(cp)) return true;
  if (cp === 0x0023 || cp === 0x002A || (cp >= 0x0030 && cp <= 0x0039)) return true;
  return false;
}

function isEmojiGlue(cp) {
  return cp === 0x200D || cp === 0xFE0E || cp === 0xFE0F;
}

function isScriptJoiner(cp) {
  return cp === 0x200C || cp === 0x200D;
}

function isTagChar(cp) {
  return cp >= 0xE0001 && cp <= 0xE007F;
}

function getCharKind(cp) {
  if (isTagChar(cp)) return "tag_chars";
  if ((cp >= 0xE0100 && cp < 0xE01F0) || (cp >= 0xFE00 && cp <= 0xFE0F) || (cp >= 0x180B && cp <= 0x180D)) return "variation_selector";
  if (BIDI_CODEPOINTS.has(cp)) return "bidi";
  if (ZW_FAMILY.has(cp)) return "zwj_family";
  if (isPrivateUse(cp)) return "private_use";
  if (SPACE_HOMOGLYPHS[cp]) return "space";
  return "strip";
}

function getCharLabel(cp) {
  const hex = "U+" + cp.toString(16).toUpperCase().padStart(4, "0");
  const knownNames = {
    0x00AD: "SOFT HYPHEN",
    0x200B: "ZERO WIDTH SPACE",
    0x200C: "ZERO WIDTH NON-JOINER",
    0x200D: "ZERO WIDTH JOINER",
    0x200E: "LEFT-TO-RIGHT MARK",
    0x200F: "RIGHT-TO-LEFT MARK",
    0x2060: "WORD JOINER",
    0xFEFF: "ZERO WIDTH NO-BREAK SPACE (BOM)",
    0x00A0: "NO-BREAK SPACE",
    0x3000: "IDEOGRAPHIC SPACE",
  };
  return `${hex} ${knownNames[cp] || (isPrivateUse(cp) ? "PRIVATE USE AREA" : "INVISIBLE/FORMAT")}`;
}

