// Processing Single File (Dispatcher)
window.processSingleFile = async function(id) {
  const item = AppState.files.find(f => f.id === id);
  if (!item) return;

  const summaryEl = document.getElementById(`summary_${id}`);
  const downloadBtn = document.getElementById(`download_${id}`);
  summaryEl.innerHTML = `<span>⏳ 正在处理中...</span>`;

  try {
    const ext = item.name.split(".").pop().toLowerCase();

    // 1. Text / Markdown / HTML / SVG
    if (["txt", "js", "py", "json"].includes(ext)) {
      const text = await item.file.text();
      const res = cleanTextEngine(text);
      item.cleanedText = res.cleanedText;
      item.cleanedBlob = new Blob([res.cleanedText], { type: "text/plain;charset=utf-8" });
      summaryEl.innerHTML = `<span>✅ 剥离隐式字符: <strong>${res.removedCount}</strong> 处</span>`;
    } else if (["md", "markdown"].includes(ext)) {
      const text = await item.file.text();
      const res = cleanMarkdownEngine(text);
      item.cleanedText = res.cleanedText;
      item.cleanedBlob = new Blob([res.cleanedText], { type: "text/markdown;charset=utf-8" });
      summaryEl.innerHTML = `<span>✅ 净化 Frontmatter AI 键并清除隐式字符</span>`;
    } else if (["html", "htm"].includes(ext)) {
      const text = await item.file.text();
      const res = cleanHTMLEngine(text);
      item.cleanedText = res.cleanedText;
      item.cleanedBlob = new Blob([res.cleanedText], { type: "text/html;charset=utf-8" });
      summaryEl.innerHTML = `<span>✅ 剥离 AI Meta、JSON-LD 与自定义属性</span>`;
    } else if (ext === "svg") {
      const text = await item.file.text();
      const res = cleanSVGEngine(text);
      item.cleanedText = res.cleanedText;
      item.cleanedBlob = new Blob([res.cleanedText], { type: "image/svg+xml;charset=utf-8" });
      summaryEl.innerHTML = `<span>✅ 剥离 &lt;metadata&gt;、XMP 与 AI 注释</span>`;
    } 
    // 2. Images (PNG, JPEG)
    else if (ext === "png") {
      const buffer = await item.file.arrayBuffer();
      const res = cleanPNGBinary(buffer);
      item.cleanedBlob = new Blob([res.cleanedBytes], { type: "image/png" });
      summaryEl.innerHTML = `<span>✅ 剥离 C2PA (JUMBF) 与 AI Chunks (${res.actions.length} 项)</span>`;
    } else if (["jpg", "jpeg"].includes(ext)) {
      const buffer = await item.file.arrayBuffer();
      const res = cleanJPEGBinary(buffer);
      item.cleanedBlob = new Blob([res.cleanedBytes], { type: "image/jpeg" });
      summaryEl.innerHTML = `<span>✅ 剥离 APP11/APP1 C2PA 与 EXIF AI 标记</span>`;
    }
    // 3. Office DOCX
    else if (ext === "docx") {
      const buffer = await item.file.arrayBuffer();
      const res = await cleanDOCXPackage(buffer);
      item.cleanedBlob = new Blob([res.cleanedBytes], { type: "application/vnd.openxmlformats-officedocument.wordprocessingml.document" });
      summaryEl.innerHTML = `<span>✅ 剥离 docProps、customXml 与生成器数据</span>`;
    }
    // 4. PDF (Requires Backend for qpdf Linearize)
    else if (ext === "pdf") {
      if (AppState.backendOnline) {
        summaryEl.innerHTML = `<span>🚀 正在通过 Python 后端执行 qpdf 物理级重构...</span>`;
        const res = await callBackendClean(item.file);
        item.cleanedBlob = res.blob;
        summaryEl.innerHTML = `<span>✅ qpdf 物理重构完成，元数据对象已消除</span>`;
      } else {
        summaryEl.innerHTML = `<span>⚠️ 提示：PDF 彻底消除需启动本地后端以执行 qpdf 重建</span>`;
        item.cleanedBlob = item.file; // fallback
      }
    }

    item.status = "cleaned";
    downloadBtn.style.display = "inline-flex";
  } catch (err) {
    summaryEl.innerHTML = `<span class="text-danger">❌ 处理失败: ${err.message}</span>`;
  }
};

window.downloadFileResult = function(id) {
  const item = AppState.files.find(f => f.id === id);
  if (!item || !item.cleanedBlob) return;

  const url = URL.createObjectURL(item.cleanedBlob);
  const a = document.createElement("a");
  const parts = item.name.split(".");
  const ext = parts.pop();
  a.download = `${parts.join(".")}.cleaned.${ext}`;
  a.href = url;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
};

window.inspectSingleFile = async function(id) {
  const item = AppState.files.find(f => f.id === id);
  if (!item) return;

  const modal = document.getElementById("modal-inspect");
  const body = document.getElementById("inspect-modal-body");
  const title = document.getElementById("inspect-modal-title");
  title.textContent = `🔍 检视报告: ${item.name}`;

  body.innerHTML = "<p>正在解析文件结构与元数据...</p>";
  modal.classList.remove("hidden");

  let findings = [];
  const ext = item.name.split(".").pop().toLowerCase();

  if (["txt", "md", "html", "js", "py"].includes(ext)) {
    const text = await item.file.text();
    const res = cleanTextEngine(text);
    findings = res.hits.map(h => `[${h.kind}/${h.confidence}] ${h.label} 出现 ${h.count} 次`);
  } else if (ext === "png") {
    findings.push("检查 PNG 专用 Chunks (caBX, juMB, iTXt, eXIf)");
  } else if (["jpg", "jpeg"].includes(ext)) {
    findings.push("检查 JPEG APP11 (C2PA/JUMBF) 与 APP1 (EXIF/XMP)");
  } else if (ext === "docx") {
    findings.push("检查 DOCX 压缩包内 customXml/ 与 docProps/*.xml");
  }

  body.innerHTML = `
    <div class="inspect-report-view">
      <h4>文件属性</h4>
      <p><strong>文件名称:</strong> ${item.name}</p>
      <p><strong>文件大小:</strong> ${(item.size / 1024).toFixed(2)} KB</p>
      <hr class="divider">
      <h4>溯源与标记检测清单</h4>
      <ul>
        ${findings.length > 0 ? findings.map(f => `<li>${f}</li>`).join("") : "<li>未发现可疑的隐式字符或 C2PA 存证标识</li>"}
      </ul>
    </div>
  `;

  document.getElementById("btn-inspect-modal-clean").onclick = () => {
    modal.classList.add("hidden");
    processSingleFile(id);
  };
  document.getElementById("btn-close-inspect-modal").onclick = () => modal.classList.add("hidden");
  document.getElementById("btn-inspect-modal-close").onclick = () => modal.classList.add("hidden");
};

