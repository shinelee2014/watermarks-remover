// Tab Switching
function initTabs() {
  const tabButtons = document.querySelectorAll(".tab-btn");
  tabButtons.forEach(btn => {
    btn.addEventListener("click", () => {
      tabButtons.forEach(b => {
        b.classList.remove("active");
        b.setAttribute("aria-selected", "false");
      });
      document.querySelectorAll(".tab-panel").forEach(p => p.classList.remove("active"));

      btn.classList.add("active");
      btn.setAttribute("aria-selected", "true");
      const targetId = btn.getAttribute("data-target");
      document.getElementById(targetId).classList.add("active");
    });
  });
}

// Dropzone & File Handling
function initDropzone() {
  const dropzone = document.getElementById("dropzone");
  const fileInput = document.getElementById("file-input");

  ["dragenter", "dragover"].forEach(event => {
    dropzone.addEventListener(event, (e) => {
      e.preventDefault();
      dropzone.classList.add("dragover");
    });
  });

  ["dragleave", "drop"].forEach(event => {
    dropzone.addEventListener(event, (e) => {
      e.preventDefault();
      dropzone.classList.remove("dragover");
    });
  });

  dropzone.addEventListener("drop", (e) => {
    if (e.dataTransfer.files && e.dataTransfer.files.length > 0) {
      handleIncomingFiles(e.dataTransfer.files);
    }
  });

  fileInput.addEventListener("change", (e) => {
    if (e.target.files && e.target.files.length > 0) {
      handleIncomingFiles(e.target.files);
    }
  });

  document.getElementById("btn-clean-all").addEventListener("click", cleanAllFiles);
  document.getElementById("btn-clear-list").addEventListener("click", clearFileList);
}

function handleIncomingFiles(fileList) {
  for (let file of fileList) {
    const fileId = "file_" + Math.random().toString(36).substr(2, 9);
    AppState.files.push({
      id: fileId,
      file: file,
      name: file.name,
      size: file.size,
      type: detectFileType(file.name),
      status: "ready",
      report: null,
      cleanedBlob: null,
      cleanedText: null
    });
  }
  updateFileListView();
}

function detectFileType(name) {
  const ext = name.split(".").pop().toLowerCase();
  if (["png", "jpg", "jpeg", "webp"].includes(ext)) return "image";
  if (ext === "svg") return "svg";
  if (["md", "markdown", "txt", "js", "py", "html", "htm"].includes(ext)) return "text";
  if (["docx", "odt"].includes(ext)) return "docx";
  if (ext === "pdf") return "pdf";
  return "binary";
}

